"""Inspect PostgreSQL catalog: tables, RLS policies, user-defined vs internal triggers, roles."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy import text

from app.core.database import get_admin_engine


def main():
    engine = get_admin_engine()
    with engine.connect() as conn:
        print("PG VERSION:", conn.execute(text("SELECT version()")).scalar())

        # Table inventory
        tables = conn.execute(text("""
            SELECT table_schema, table_name, table_type 
            FROM information_schema.tables 
            WHERE table_schema NOT IN ('pg_catalog', 'information_schema')
            ORDER BY table_schema, table_name;
        """)).fetchall()
        print(f"\nTABLES (count = {len(tables)}):")
        for t in tables:
            print(f"  {t[0]}.{t[1]} ({t[2]})")

        # RLS status on tables
        rls = conn.execute(text("""
            SELECT relname, relrowsecurity, relforcerowsecurity 
            FROM pg_class 
            JOIN pg_namespace ON pg_namespace.oid = pg_class.relnamespace
            WHERE nspname = 'public' AND relkind = 'r'
            ORDER BY relname;
        """)).fetchall()
        print(f"\nRLS ON PUBLIC TABLES (count = {len(rls)}):")
        for r in rls:
            print(f"  {r[0]}: rls={r[1]}, force={r[2]}")

        # Policies count & list
        policies = conn.execute(text("""
            SELECT schemaname, tablename, policyname, permissive, roles, cmd 
            FROM pg_policies 
            ORDER BY tablename, policyname;
        """)).fetchall()
        print(f"\nPG POLICIES (count = {len(policies)}):")
        for p in policies:
            print(f"  {p[1]} -> {p[2]} ({p[5]}, roles: {p[4]})")

        # Triggers investigation
        triggers = conn.execute(text("""
            SELECT tgname, relname, tgtype, tgenabled, tgisinternal
            FROM pg_trigger
            JOIN pg_class ON pg_class.oid = pg_trigger.tgrelid
            JOIN pg_namespace ON pg_namespace.oid = pg_class.relnamespace
            WHERE nspname = 'public'
            ORDER BY tgisinternal, relname, tgname;
        """)).fetchall()
        print(f"\nTOTAL TRIGGERS IN PUBLIC SCHEMA: {len(triggers)}")
        user_trigs = [tr for tr in triggers if not tr[4]]
        internal_trigs = [tr for tr in triggers if tr[4]]
        print(f"  User-defined triggers ({len(user_trigs)}):")
        for ut in user_trigs:
            print(f"    {ut[1]} -> {ut[0]}")
        print(f"  Internal constraint triggers generated by PostgreSQL ({len(internal_trigs)}):")
        for it in internal_trigs[:10]:
            print(f"    {it[1]} -> {it[0]}")
        if len(internal_trigs) > 10:
            print(f"    ... and {len(internal_trigs) - 10} more FK/PK constraint triggers.")

        # Roles and grants
        roles = conn.execute(text("""
            SELECT rolname, rolsuper, rolinherit, rolcreaterole, rolcreatedb, rolcanlogin, rolbypassrls
            FROM pg_roles
            WHERE rolname IN ('postgres', 'scenesteward', 'scenesteward_app')
            ORDER BY rolname;
        """)).fetchall()
        print("\nROLES:")
        for ro in roles:
            print(f"  {ro[0]}: super={ro[1]}, bypassrls={ro[6]}, canlogin={ro[5]}")

        # Current Alembic revision
        elem = conn.execute(text("SELECT version_num FROM alembic_version;")).fetchall()
        print(f"\nALEMBIC VERSION IN DB: {[e[0] for e in elem]}")

if __name__ == "__main__":
    main()
